#!/usr/bin/env bash
#
# Brings up the Countflow demo — one command, no arguments.
#
#   ./scripts/demo.sh
#
# On first run it writes .env.demo with freshly generated secrets and leaves it
# there; on every run after that it reuses them, so the database, the sessions
# and the API keys survive a restart. .env.demo is gitignored and must stay that
# way: it holds three machine credentials and a signing key.
#
# To point the demo at a domain, set CADDY_SITE_ADDRESS in .env.demo to the
# hostname and point that hostname's A record at this host. Caddy provisions and
# renews the certificate on its own. See docs/api/hosting.md.

set -euo pipefail
umask 077

cd "$(dirname "$0")/.."

ENV_FILE=".env.demo"

# 32 bytes of CSPRNG output, base64url. The same shape the API mints an API key
# in, and long enough that the seeder's length check passes for the right reason
# rather than by luck.
secret() {
  openssl rand -base64 32 | tr '+/' '-_' | tr -d '=\n'
}

if [[ ! -f "$ENV_FILE" ]]; then
  echo "Generating $ENV_FILE …"

  cat > "$ENV_FILE" <<EOF
# Generated by scripts/demo.sh. Not for version control — this holds three
# machine credentials, a signing key and two passwords.
#
# The demo is public: anybody who reaches it can sign in with DEMO_PASSWORD and
# change what everybody else sees. That is intended. Do not put anything here
# that is also true anywhere else.

# The hostname Caddy serves. ":80" serves plain HTTP on every name, which is
# right for a laptop and wrong for the internet — set a real hostname and Caddy
# will provision TLS for it automatically.
CADDY_SITE_ADDRESS=:80

POSTGRES_PASSWORD=$(secret)
JWT_SIGNING_KEY=$(secret)
SEQ_ADMIN_PASSWORD=$(secret)
WEBHOOKS_ENCRYPTION_KEY=$(openssl rand -base64 32)

# Shown on the demo's login screen, so it is deliberately memorable rather than
# random. It is the credential for three accounts that can change a public
# warehouse and nothing else.
DEMO_PASSWORD=Countflow#2026

# One per role. The simulator holds all three and uses each for the work that
# role is allowed to do — see the note in compose.demo.yaml.
DEMO_ADMIN_API_KEY=cfk_$(secret)
DEMO_SUPERVISOR_API_KEY=cfk_$(secret)
DEMO_OPERATOR_API_KEY=cfk_$(secret)

# How much warehouse to build. The seed is fixed so the demo somebody was shown
# last week and the one they come back to are the same building.
DEMO_WAREHOUSE=WH1
DEMO_DAYS=4
DEMO_SEED=20260812
EOF

  chmod 600 "$ENV_FILE"
  echo "Wrote $ENV_FILE. Read it before exposing this host — CADDY_SITE_ADDRESS is :80 by default."
fi

# --env-file, and both compose files named explicitly. Naming them is what skips
# compose.override.yaml; without that, the development overlay would publish the
# database port on a public host.
exec docker compose --project-name countflow-demo --env-file "$ENV_FILE" \
  -f compose.yaml -f compose.demo.yaml \
  up -d --build "$@"
